# --- PDF Report Class ---
class PDFReport(FPDF):

  def header(self):
    self.set_fill_color(30, 41, 59)
    self.rect(0, 0, 297, 20, "F")
    self.set_font("Helvetica", "B", 15)
    self.set_text_color(255, 255, 255)
    self.cell(
        0, 6, "HoneyShield: AI SOC Threat Intelligence Report", ln=1, align="C"
    )
    self.set_font("Helvetica", "", 9)
    self.set_text_color(148, 163, 184)
    self.cell(
        0,
        4,
        "Real-Time IoT Honeypot Log & AI Classification Analysis",
        ln=1,
        align="C",
    )
    self.ln(6)

  def footer(self):
    self.set_y(-12)
    self.set_font("Helvetica", "I", 8)
    self.set_text_color(148, 163, 184)
    self.cell(
        0,
        10,
        f"Page {self.page_no()} | Generated by HoneyShield AI SOC System",
        align="C",
    )


def generate_pdf_report(df, filter_label):
  pdf = PDFReport(orientation="L", unit="mm", format="A4")
  pdf.set_auto_page_break(auto=True, margin=15)
  pdf.add_page()

  clean_label = (
      str(filter_label)
      .replace("📅", "")
      .replace("⚡", "")
      .replace("📜", "")
      .strip()
  )

  total_attacks = len(df)
  unique_ips = (
      df["src_ip"].nunique() if ("src_ip" in df.columns and not df.empty) else 0
  )
  top_threat = (
      df["ai_attack_type"].mode()[0]
      if (
          "ai_attack_type" in df.columns
          and not df.empty
          and not df["ai_attack_type"].empty
      )
      else "N/A"
  )
  avg_conf = (
      f"{df['ai_confidence'].mean():.1f}%"
      if ("ai_confidence" in df.columns and not df.empty)
      else "N/A"
  )

  pdf.set_fill_color(241, 245, 249)
  pdf.set_draw_color(203, 213, 225)
  pdf.rect(10, 24, 277, 18, "DF")

  pdf.set_xy(12, 26)
  pdf.set_font("Helvetica", "B", 9)
  pdf.set_text_color(71, 85, 105)
  pdf.cell(69, 4, "TOTAL ATTACKS LOGGED", align="C")
  pdf.cell(69, 4, "UNIQUE ATTACKER IPS", align="C")
  pdf.cell(69, 4, "PRIMARY THREAT CATEGORY", align="C")
  pdf.cell(69, 4, "AVG AI CONFIDENCE", align="C", ln=1)

  pdf.set_x(12)
  pdf.set_font("Helvetica", "B", 12)
  pdf.set_text_color(37, 99, 235)
  pdf.cell(69, 8, str(total_attacks), align="C")
  pdf.set_text_color(5, 150, 105)
  pdf.cell(69, 8, str(unique_ips), align="C")
  pdf.set_text_color(220, 38, 38)
  pdf.cell(69, 8, str(top_threat), align="C")
  pdf.set_text_color(217, 119, 6)
  pdf.cell(69, 8, str(avg_conf), align="C", ln=1)

  pdf.ln(8)

  pdf.set_font("Helvetica", "B", 11)
  pdf.set_text_color(15, 23, 42)
  pdf.cell(0, 7, f"Detailed Attack Logs ({clean_label})", ln=1)

  pdf.set_font("Helvetica", "B", 9)
  pdf.set_fill_color(30, 41, 59)
  pdf.set_text_color(255, 255, 255)

  col_w = [38, 28, 22, 68, 42, 50, 29]
  headers = [
      "Timestamp",
      "Attacker IP",
      "User",
      "Executed Command",
      "MITRE Code",
      "AI Threat Category",
      "Confidence",
  ]

  for i, h in enumerate(headers):
    pdf.cell(col_w[i], 8, h, border=1, fill=True, align="C")
  pdf.ln()

  pdf.set_font("Helvetica", size=8.5)
  pdf.set_text_color(15, 23, 42)

  for idx, row in df.iterrows():
    fill = bool(idx % 2 == 1)
    if fill:
      pdf.set_fill_color(248, 250, 252)
    else:
      pdf.set_fill_color(255, 255, 255)

    ts = str(row.get("formatted_time", row.get("timestamp", "")))[:19]
    ip = str(row.get("src_ip", "-"))
    user = str(row.get("username", "-"))
    if user in ["nan", "None", ""]:
      user = "-"
    cmd = str(row.get("command", "-"))[:35]
    mitre = str(row.get("mitre_id", "-"))
    threat = str(row.get("ai_attack_type", "-"))
    conf_val = row.get("ai_confidence", 0)
    conf_str = (
        f"{conf_val:.1f}%" if isinstance(conf_val, (int, float)) else str(conf_val)
    )

    cmd = str(cmd).encode("latin-1", "replace").decode("latin-1")
    threat = str(threat).encode("latin-1", "replace").decode("latin-1")

    pdf.cell(col_w[0], 7, ts, border=1, fill=fill, align="C")
    pdf.cell(col_w[1], 7, ip, border=1, fill=fill, align="C")
    pdf.cell(col_w[2], 7, user, border=1, fill=fill, align="C")
    pdf.cell(col_w[3], 7, f" {cmd}", border=1, fill=fill)
    pdf.cell(col_w[4], 7, mitre, border=1, fill=fill, align="C")
    pdf.cell(col_w[5], 7, f" {threat}", border=1, fill=fill)
    pdf.cell(col_w[6], 7, conf_str, border=1, fill=fill, align="C")
    pdf.ln()

  return bytes(pdf.output())


# --- Streamlit UI Layout ---
st.sidebar.title("🛡️ SOC Dashboard Filters")

time_filter = st.sidebar.radio(
    "Select Time Window View:",
    (
        "📜 All Historical Attacks",
        "📅 Today / Last 24 Hours",
        "⚡ Latest Attacks (Last 1 Hour)",
    ),
    index=0,
)

st.sidebar.markdown("---")

# Fetch Database Logs
conn = sqlite3.connect("honeyshield.db")
try:
  df = pd.read_sql_query("SELECT * FROM attacks ORDER BY id DESC", conn)
except Exception:
  df = pd.DataFrame()
conn.close()

if not df.empty:
  df["parsed_time"] = pd.to_datetime(
      df["timestamp"].astype(str).str.replace("Z", "").str.replace("T", " "),
      errors="coerce",
  )
  df["formatted_time"] = df["parsed_time"].dt.strftime("%Y-%m-%d %H:%M:%S")

  now = datetime.now()

  if "Last 1 Hour" in time_filter:
    cutoff = now - timedelta(hours=1)
    filtered_df = df[df["parsed_time"] >= cutoff]
    if not filtered_df.empty:
      df = filtered_df
  elif "Last 24 Hours" in time_filter:
    cutoff = now - timedelta(hours=24)
    filtered_df = df[df["parsed_time"] >= cutoff]
    if not filtered_df.empty:
      df = filtered_df

# Sidebar Buttons
if not df.empty:
  pdf_bytes = generate_pdf_report(df, time_filter)
  st.sidebar.download_button(
      label="📄 Download Threat Report (PDF)",
      data=pdf_bytes,
      file_name="HoneyShield_Threat_Report.pdf",
      mime="application/pdf",
      use_container_width=True,
  )
  st.sidebar.markdown("---")

